# Level-matches the factory presets.
# Reads the levels.tsv written by RenderTest and regenerates Source/PresetTrims.inc so
# every preset lands near the same short-term loudness with peaks below -3 dBFS.
#
#   RenderTest.exe <deSIDuous.vst3> renders
#   powershell -File tools\level-presets.ps1 [-Levels renders\levels.tsv]
#   (rebuild, then run RenderTest again to check)
#
# Trims accumulate: an existing trim is kept and the new correction is added to it.

param(
    [string]$Levels = "$PSScriptRoot\..\renders\levels.tsv",
    [string]$Trims  = "$PSScriptRoot\..\Source\PresetTrims.inc",
    [double]$SingleTarget = -18.0,   # short-term RMS for single-note presets
    [double]$ChordTarget  = -16.0,   # ... and for presets measured with a chord
    [double]$PeakCeiling  = -3.0,
    [double]$Tolerance    = 0.75     # leave presets this close to target alone
)

$existing = @{}
if (Test-Path $Trims) {
    foreach ($line in Get-Content $Trims) {
        if ($line -match '^\s*\{\s*"(.+)",\s*([-\d.]+)f\s*\},') { $existing[$Matches[1]] = [double]$Matches[2] }
    }
}

$out = New-Object System.Collections.Generic.List[string]
$out.Add('// Generated by tools/level-presets.ps1 - do not edit by hand.')
$changed = 0
foreach ($row in Get-Content $Levels) {
    $name, $kind, $peak, $rms = $row.Split("`t")
    if (-not $name) { continue }
    $peak = [double]$peak; $rms = [double]$rms
    $target = if ($kind -eq 'chord') { $ChordTarget } else { $SingleTarget }

    $delta = $target - $rms
    $delta = [Math]::Min($delta, $PeakCeiling - $peak)          # never push peaks past the ceiling
    if ([Math]::Abs($delta) -lt $Tolerance) { $delta = 0.0 } else { $changed++ }

    $trim = [Math]::Round((($existing[$name] -as [double]) + $delta) * 2.0) / 2.0   # 0.5 dB steps
    $trim = [Math]::Max(-24.0, [Math]::Min(12.0, $trim))   # same range as the Output Gain parameter
    if ($trim -ne 0.0) {
        $escaped = $name.Replace('\', '\\').Replace('"', '\"')
        $out.Add(('{{ "{0}", {1}f }},' -f $escaped, $trim.ToString('0.0', [Globalization.CultureInfo]::InvariantCulture)))
    }
}
[IO.File]::WriteAllLines((Resolve-Path -LiteralPath (Split-Path $Trims)).Path + '\' + (Split-Path $Trims -Leaf), $out)
"{0} preset(s) corrected, {1} trim entries written" -f $changed, ($out.Count - 1)
